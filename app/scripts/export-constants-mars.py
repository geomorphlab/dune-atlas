"""Export the Mars constants to app/src/generated/constants-mars.json (the browser Mars physics,
src/cell/marsphysics.ts, must use exactly pipeline/src/dune_atlas_pipeline/mars/constants.py).

    PYTHONPATH=pipeline/src python app/scripts/export-constants-mars.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline" / "src"))
from dune_atlas_pipeline.mars import constants as M, physics as P  # noqa: E402

KEYS = ["G", "R_MARS", "R_AIR", "MU0", "T0_MU", "S_MU", "K_ADIABATIC", "RHO_P", "KAPPA", "MIX_DAMP",
        "DSTAR_MIN", "UPLUS_MIN", "C1", "C2", "KN_A", "KN_B", "KN_C", "GA_SQRT_S_MIN", "BETA", "DASPECT", "S2Y",
        "D_DEFAULT_INDEX"]
out = {"_comment": "GENERATED by app/scripts/export-constants-mars.py from pipeline mars/constants.py - do not edit"}
out.update({k: float(getattr(M, k)) if k != "D_DEFAULT_INDEX" else int(M.D_DEFAULT_INDEX) for k in KEYS})
out["D_VALUES_UM"] = [int(v) for v in M.D_VALUES_UM]
out["SERIES_VARS"] = list(M.SERIES_VARS)
# eq. 2.2 smooth-wall profile (pipeline mars/profile_table.json) and the u* bisection settings
out["PROFILE_LN_X"] = P.LN_X.tolist()
out["PROFILE_U_PLUS"] = P.U_PLUS.tolist()
out["N_BISECT"] = int(P.N_BISECT)
out["LN_US_LO"], out["LN_US_HI"] = float(P.LN_US_LO), float(P.LN_US_HI)
dst = ROOT / "app" / "src" / "generated" / "constants-mars.json"
dst.write_text(json.dumps(out, indent=1) + "\n")
print(dst, len(out))
