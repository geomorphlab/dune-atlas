"""Build tests/fixtures/mars-physics-parity.json: reference values of the Mars physics (pipeline mars/physics.py)
on a deterministic grid of states (u, v, T, rho, ps) x grain diameters, for the TS port (src/bodies/mars/marsphysics.ts).

    PYTHONPATH=pipeline/src python app/scripts/make-mars-physics-fixture.py
"""
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline" / "src"))
from dune_atlas_pipeline.mars import constants as M, physics as P  # noqa: E402

rng = np.random.default_rng(20261014)
n = 400
u = rng.normal(0, 8, n); v = rng.normal(0, 8, n)
T = rng.uniform(140, 300, n); rho = rng.uniform(0.0030, 0.032, n)
d = M.D_VALUES[rng.integers(0, 64, n)]
d[:5] = M.D_VALUES[[0, 29, 63, 10, 50]]
ps = rng.uniform(200, 1200, n)
ak = (0.0, 1.0, 2.5, 0.995)  # synthetic hybrid interfaces (ak_lo, bk_lo, ak_hi, bk_hi)
z = P.layer_height(ps, T, *ak)
nu = P.viscosity(T) / rho
ustar, ua = P.friction_velocity(u, v, z, nu)
xs = np.exp(np.linspace(np.log(1e-4), np.log(1e10), 300))   # u+ profile probes incl. both extrapolations
q, th = P.flux(ustar, d, rho, T)
q_nokn, th0 = P.flux(ustar, d, rho, T, knudsen=False)
p, rho_air = P.air_state(ps, T, *ak)
rows = []
for i in range(n):
    rows.append({k: float(x[i]) for k, x in [("u", u), ("v", v), ("T", T), ("rho", rho), ("d", d), ("ps", ps),
                                              ("z", z), ("nu", nu),
                                              ("ustar", ustar), ("ua", ua), ("q", q), ("q_nokn", q_nokn),
                                              ("ut", th["ut"]), ("ut_nokn", th0["ut"]), ("dstar", th["dstar"]),
                                              ("kn", th["kn"]), ("fkn", th["fkn"]), ("ga_sqrt_s", th["ga_sqrt_s"]),
                                              ("mu", P.viscosity(T)), ("p", p), ("rho_air", rho_air)]})
out = {"_comment": "GENERATED by app/scripts/make-mars-physics-fixture.py", "ak": list(ak),
       "n_positive": int((q > 0).sum()), "rows": rows,
       "profile": {"x": xs.tolist(), "u_plus": P.u_plus(xs).tolist()}}
dst = ROOT / "app" / "tests" / "fixtures" / "mars-physics-parity.json"
dst.write_text(json.dumps(out) + "\n")
print(dst, n, out["n_positive"])
