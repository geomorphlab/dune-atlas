"""Write app/src/core/generated/colormaps.json: named colormaps as 256 hex stops (matplotlib).

Names are what registry `display.colormap` may use. Re-run to add a colormap:
    python app/scripts/gen-colormaps.py
"""
import json
import pathlib

import matplotlib
from matplotlib.colors import to_hex
import numpy as np

NAMES = {  # registry name -> matplotlib name
    "viridis": "viridis", "magma": "magma", "inferno": "inferno", "plasma": "plasma",
    "cividis": "cividis", "twilight": "twilight", "twilight_shifted": "twilight_shifted",
    "rdbu": "RdBu_r", "puor": "PuOr_r", "brbg": "BrBG", "piyg": "PiYG", "ylorbr": "YlOrBr", "ylgn": "YlGn", "greys": "Greys",
    "turbo": "turbo", "hsv": "hsv",
}
out = {"_comment": "GENERATED by app/scripts/gen-colormaps.py (matplotlib %s)" % matplotlib.__version__}
for k, v in NAMES.items():
    cm = matplotlib.colormaps[v]
    out[k] = [to_hex(cm(x)) for x in np.linspace(0, 1, 256)]
dst = pathlib.Path(__file__).resolve().parents[1] / "src" / "core" / "generated" / "colormaps.json"
dst.write_text(json.dumps(out, separators=(",", ":")) + "\n")
print(dst, len(NAMES))
