"""Build tests/fixtures/flux-parity.json: reference flux results from pipeline flux.py.

Reads histograms and fields from the fixture cell store (staging/fixture/cells.zarr), computes
DP/RDP/RDD, the per-direction flux rose, crest-flux roses and the excess-shear split at several
thresholds using the Python reference implementation, and stores the histograms sparsely (flat
index um*128+ua, count) so the TS port can be tested without the store. The cell-store fields
(dpm, rdpm, rdpa, qha_rdp_dp, crest-mode angles and fluxes; float32) are included for the check
that the app's computation from the histogram matches the map fields.

    PYTHONPATH=pipeline/src python app/scripts/make-parity-fixture.py [staging/fixture/cells.zarr]
"""
import os
import json
import math
import pathlib
import sys

import numpy as np
import zarr

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline" / "src"))
from dune_atlas_pipeline import constants as C, flux  # noqa: E402

store = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "staging" / "fixture" / "cells.zarr")
UT_IDX = [0, 5, 14, 25, 40, 63]
Y0, Y1, X0, X1 = 1056, 1216, 1904, 2000  # fixture cell region (cli.FIXTURE_CELLS)

g = zarr.open_group(store, mode="r")
FV = g.attrs["field_vars"]
fields = g["fields"][Y0:Y1, X0:X1]           # (y, x, n_fields, 64) float32
dunes = g["dunes"][Y0:Y1, X0:X1]
land = np.isfinite(fields).any((2, 3))
dpm14 = np.where(land, fields[:, :, FV.index("dpm"), 14].astype(np.float64), np.nan)

def pick():
    cells = {"decode_reference": (1100, 1950)}
    dm = np.where(dunes == 1, dpm14, np.nan)
    iy, ix = np.unravel_index(np.nanargmax(dm), dm.shape); cells["dune_max_dp"] = (Y0 + iy, X0 + ix)
    med = np.nanmedian(dm); iy, ix = np.unravel_index(np.nanargmin(np.abs(dm - med)), dm.shape)
    cells["dune_median_dp"] = (Y0 + iy, X0 + ix)
    iy, ix = np.unravel_index(np.nanargmin(dpm14), dpm14.shape); cells["land_min_dp"] = (Y0 + iy, X0 + ix)
    rng = np.random.default_rng(0)
    ys, xs = np.nonzero(land); k = rng.integers(len(ys)); cells["random_land"] = (Y0 + ys[k], X0 + xs[k])
    cells["random_land_2"] = (Y0 + ys[(k * 7919) % len(ys)], X0 + xs[(k * 7919) % len(ys)])
    return cells

cells = pick()
# No real cell has an empty direction bin (75 years of hourly winds), so add a synthetic
# histogram with 40 empty direction bins (zero petals there).
SYNTHETIC = {"synthetic_empty_dirs": cells["land_min_dp"]}

def nn(a):
    return [None if not math.isfinite(v) else float(v) for v in np.asarray(a, float)]

out = {"_comment": "GENERATED by app/scripts/make-parity-fixture.py from pipeline flux.py; 'fields' = cell-store fields (float32)", "ut_index": UT_IDX,
       "ut_values": [float(C.UT_VALUES[i]) for i in UT_IDX], "cells": []}
for name, (y, x) in list(cells.items()) + list(SYNTHETIC.items()):
    y, x = int(y), int(x)
    h = g["hist"][y, x].astype(np.int64)
    if name in SYNTHETIC:
        h[:, 20:60] = 0
    nz = np.flatnonzero(h)
    rec = {"name": name, "iy": y, "ix": x, "lat": round(90 - 0.1 * y, 6), "lon": round(-180 + 0.1 * x, 6),
           "dune": int(g["dunes"][y, x]), "hist_sum": int(h.sum()), "empty_dirs": int((h.sum(0) == 0).sum()),
           "hist_idx": nz.tolist(), "hist_cnt": h.ravel()[nz].tolist()}
    rec["synthetic"] = name in SYNTHETIC
    if name not in SYNTHETIC:
        # cell-store fields (float32): what the map shows
        fv = FV
        cf = g["fields"][y, x]
        rec["fields"] = {v: nn(cf[fv.index(v), UT_IDX]) for v in ("dpm", "rdpm", "rdpa", "qha_rdp_dp") if v in fv}
        # crest flux with speed-up for the elongation (ae) and bed/transverse (ab) modes, using the
        # cell-store float32 mode angles at each threshold; plus the crest-flux fields
        crest = {}
        for mode, av in (("elongation", "ae"), ("transverse", "ab")):
            res = []
            for i in UT_IDX:
                alpha = float(cf[fv.index(av), i])
                if not math.isfinite(alpha):
                    res.append(None); continue
                rose = flux.crest_flux_rose(h, C.UT_VALUES[i], alpha)
                res.append({"alpha": alpha, "qd": nn(rose), "total": float(rose.sum())})
            crest[mode] = res
        rec["crest"] = crest
        # flux split by excess-shear class (u*/u*,th) for one flat-bed and one crest mode
        if name in ("decode_reference", "dune_max_dp"):
            ex = []
            for i in (5, 14, 40):
                ae = float(cf[fv.index("ae"), i])
                ex.append({"ut_index": i, "ae": ae,
                           "flat": [nn(r) for r in flux.flux_rose_by_excess_shear(h, C.UT_VALUES[i])],
                           "elongation": [nn(r) for r in flux.flux_rose_by_excess_shear(h, C.UT_VALUES[i], ae)]})
            rec["excess"] = {"edges": [float(e) if math.isfinite(e) else None for e in flux.EXCESS_SHEAR_EDGES], "cases": ex}
        rec["fields_crest"] = {v: nn(cf[fv.index(v), UT_IDX]) for v in ("ab", "ae", "qalb", "qacb", "qale", "qace", "qnlb", "qncb", "qnle")}
    res = []
    for i in UT_IDX:
        ut = C.UT_VALUES[i]
        dp, rdp, rdd = flux.dp_rdp_rdd(h, ut)
        res.append({"dp": float(dp), "rdp": float(rdp), "rdd": float(rdd), "qd": nn(flux.flux_rose(h, ut))})
    rec["flux"] = res
    out["cells"].append(rec)
    print(name, y, x, "dune", rec["dune"], "nnz", len(nz), "empty_dirs", rec["empty_dirs"])

dst = ROOT / "app" / "tests" / "fixtures" / "flux-parity.json"
dst.write_text(json.dumps(out, separators=(",", ":")) + "\n")
print(dst, round(dst.stat().st_size / 1024), "kB")
