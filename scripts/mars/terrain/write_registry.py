"""Write the Terrain registry fragments registry/mars/generated/{dunes.yaml, x_elevation.yaml}.

    PYTHONPATH=pipeline/src python scripts/mars/terrain/write_registry.py \
        --dunes-summary staging/mars/terrain/dunes/dunes_summary.json
"""
import argparse
import json
from pathlib import Path

import yaml

from dune_atlas_pipeline.mars import dunes, terrain

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "registry" / "mars" / "generated"
HEAD = ("# GENERATED by scripts/mars/terrain/write_registry.py ({fn}). Do not edit by hand.\n"
        "# Fragment {{groups, layers}} merged into registry/mars/layers.yaml (same schema as registry/earth/generated/*.yaml);\n"
        "# each layer validates against registry/layers.schema.json $defs/layer.\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dunes-summary", required=True)
    a = p.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    s = json.load(open(a.dunes_summary))
    d = OUT / "dunes.yaml"
    d.write_text(HEAD.format(fn="mars.dunes.registry_fragment") +
                 "# Vector features: MVT feature id = field id (1 = largest); properties src_fid, area_km2 (spherical,\n"
                 "# Mars 2000 sphere), lon, lat (area centroid), west/south/east/north (bbox; west > east across +-180).\n"
                 + yaml.safe_dump(dunes.registry_fragment(s), sort_keys=False, allow_unicode=True, width=110))
    e = OUT / "x_elevation.yaml"
    e.write_text(HEAD.format(fn="mars.terrain.registry_fragment") +
                 "# elevation: 2-D (y, x) GeoZarr native pyramid, 1/64 deg, metres (thresholdAware: false).\n"
                 + yaml.safe_dump(terrain.registry_fragment(), sort_keys=False, allow_unicode=True, width=110))
    print(d, e)


if __name__ == "__main__":
    main()
