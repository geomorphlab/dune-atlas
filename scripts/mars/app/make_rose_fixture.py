"""Python reference for the Mars flux roses of the app (app/src/mars/cell/marsflux.ts), computed with
pipeline mars/physics.py and an independent numpy implementation of the binning:
direction bin = numpy.digitize(ua, UA_EDGES[1:-1]) (the Earth 128 bins), rose_j = sum_{h in j} q_h / N,
excess-shear class = numpy.digitize(u / u*,th, EDGES[1:-1]) for u > u*,th.

Writes app/tests/fixtures/mars-rose-parity.json (checked by app/tests/mars/rose-parity.test.ts):
three synthetic cells (fixture_common.py; 2,000 hours each, float32 series u, v, T, rho, z as base64, including
calm hours, directions exactly +-pi, a NaN hour, an invalid temperature and an invalid height); u* from the eq. 2.2
smooth-wall profile at the hour's height z (pipeline friction_velocity(u, v, z, nu)), grain-size indices 0/29/63,
modes flat and crest (two fixed alphas).

    python scripts/mars/app/make_rose_fixture.py
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "pipeline" / "src"))
sys.path.insert(0, str(HERE))
from dune_atlas_pipeline import constants as EC  # noqa: E402
from dune_atlas_pipeline.mars import constants as M  # noqa: E402
from dune_atlas_pipeline.mars import physics as P  # noqa: E402
import fixture_common as FC  # noqa: E402

EDGES = [1, 1.25, 1.5, 2, 3, 5, np.inf]
N = 2000
CELLS = [(40, 123), (8, 169), (68, 104)]     # Nili Patera, north polar erg, Proctor crater (contract grid)
D_IDX = [0, 29, 63]
ALPHAS = [None, 0.3, -2.0]


def series(iy, ix):
    s = FC.synth_series(iy, ix)
    out = {k: s[k][:N].astype("f4") for k in ("u", "v", "T", "rho", "z")}
    out["u"][:4] = [0.0, -7.5, -7.5, 9.0]          # calm; ua = +pi; ua = -pi (v = -0.0); due east
    out["v"][:4] = [0.0, 0.0, -0.0, 0.0]
    out["u"][4] = np.nan                            # missing hour
    out["T"][5] = 0.0                               # invalid hour
    out["z"][6] = 0.0                               # invalid height
    return out


def roses(s, d, alpha):
    u, v, T, rho, z = (s[k].astype("f8") for k in ("u", "v", "T", "rho", "z"))
    ok = np.isfinite(u) & np.isfinite(v) & (T > 0) & (rho > 0) & (z > 0)
    u, v, T, rho, z = u[ok], v[ok], T[ok], rho[ok], z[ok]
    us, ua = P.friction_velocity(u, v, z, P.viscosity(T) / rho)
    b = np.digitize(ua, EC.UA_EDGES[1:-1])
    th = P.threshold(d, rho, T)
    uu = us if alpha is None else us * (1 + M.BETA * M.DASPECT * np.abs(np.sin(ua - alpha)))
    q = P.transport_rate(uu, th["ut"], d, th["s"], th["gt"], th["nu"])
    n = ok.sum()
    rose = np.bincount(b, weights=q, minlength=128) / n
    cls = np.digitize(uu / th["ut"], EDGES[1:-1])
    classes = [np.bincount(b[(cls == c) & (uu > th["ut"])], weights=q[(cls == c) & (uu > th["ut"])], minlength=128) / n for c in range(len(EDGES) - 1)]
    ut_sorted = np.sort(th["ut"])
    stats = {"utMedian": float(np.quantile(ut_sorted, 0.5)), "utP05": float(np.quantile(ut_sorted, 0.05)), "utP95": float(np.quantile(ut_sorted, 0.95)),
             "fracAbove": float((us > th["ut"]).mean()), "fracInvalid": float((~(th["ga_sqrt_s"] > M.GA_SQRT_S_MIN)).mean())}
    return {"rose": rose.tolist(), "classes": [c.tolist() for c in classes], "nHours": int(n), "bins": b.tolist() if alpha is None and d == M.D_VALUES[0] else None, "stats": stats}


def main():
    out = {"_comment": "GENERATED by scripts/mars/app/make_rose_fixture.py (pipeline mars/physics.py) - do not edit", "cells": []}
    for iy, ix in CELLS:
        s = series(iy, ix)
        cell = {"iy": iy, "ix": ix, "series": {k: base64.b64encode(s[k].tobytes()).decode() for k in ("u", "v", "T", "rho", "z")}, "cases": []}
        for k in D_IDX:
            for a in ALPHAS:
                r = roses(s, float(M.D_VALUES[k]), a)
                cell["cases"].append({"dIndex": k, "dUm": int(M.D_VALUES_UM[k]), "alpha": a, **{x: y for x, y in r.items() if y is not None}})
        out["cells"].append(cell)
    p = REPO / "app" / "tests" / "fixtures" / "mars-rose-parity.json"
    p.write_text(json.dumps(out, separators=(",", ":")))
    print(p, p.stat().st_size)


if __name__ == "__main__":
    main()
