"""Write registry/earth/places.yaml (named search and 'Show names' labels) from the approved name table.

    python scripts/places/build_earth_places.py earth-dune-field-names-final.csv [registry/earth/places.yaml]

Columns used (all others, e.g. review scores, flags and notes, are not shipped):
  id, display_name_suggested (line 1, verbatim), display_name_line2 + line2_script_language (line 2 and its
  BCP 47 language), name_english + alternative_names (search aliases; 'name [meta]' entries separated by
  ' | ': the name is matched, name and meta are shown in the popup), countries_or_territories (';' or ','),
  lat, lon, radius_km, mapped_dune_km2, reference_urls (' | '; the non-empty ones, in order, de-duplicated),
  sub_units (' | '; shown as 'Includes: ...' and searchable, resolving to the parent; a bracketed name in
  another script is an alias too).
"""
import csv
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# line2_script_language -> BCP 47 tag (script subtag where the language is written in several scripts)
LANGS = [
    (r"^Arabic; Arabic", "ar"), (r"^Arabic; Persian", "fa"), (r"^Arabic; Urdu", "ur"), (r"^Arabic; Pashto", "ps"),
    (r"^Cyrillic; Kazakh", "kk"), (r"^Cyrillic; Russian", "ru"), (r"^Cyrillic; Mongolian", "mn-Cyrl"),
    (r"^Cyrillic; Yakut", "sah"), (r"^Cyrillic; Serbian", "sr-Cyrl"), (r"^Cyrillic; Ukrainian", "uk"),
    (r"^Cyrillic; Uzbek", "uz-Cyrl"), (r"^(Simplified Chinese|Han)", "zh-Hans"), (r"^Devanagari; Hindi", "hi"),
]


def lang_of(s: str) -> str:
    for pat, tag in LANGS:
        if re.match(pat, s):
            return tag
    raise ValueError(f"no language tag for line2_script_language {s!r}")


def split_bar(s: str) -> list[str]:
    return [x.strip() for x in s.split("|")]


def name_and_note(s: str) -> tuple[str, str | None]:
    m = re.match(r"^(.*?)\s*\[(.*)\]\s*$", s)
    return (m.group(1).strip(), m.group(2).strip()) if m else (s.strip(), None)


def num(s: str) -> float | int:
    v = float(s)
    return int(v) if v.is_integer() else round(v, 4)


def place(r: dict) -> dict:
    line1 = r["display_name_suggested"].strip()
    p: dict = {"id": r["id"].strip(), "line1": line1}
    if r["display_name_line2"].strip():
        p["line2"] = {"text": r["display_name_line2"].strip(), "lang": lang_of(r["line2_script_language"].strip())}
    aliases: list[str] = []
    alt: list[dict] = []
    if r["name_english"].strip() and r["name_english"].strip() != line1:
        aliases.append(r["name_english"].strip())
    for a in split_bar(r["alternative_names"]):
        if not a:
            continue
        n, note = name_and_note(a)
        if n:   # matched by the app with the aliases (core/search/places.ts searchNames)
            alt.append({"text": n, **({"note": note} if note else {})})
    includes: list[str] = []
    for s in split_bar(r["sub_units"]):
        if not s:
            continue
        n, extra = name_and_note(s)
        includes.append(s if not extra else f"{n} ({extra})")
        aliases.append(n)
        if extra and ";" not in extra:   # a name in another script, e.g. 'Cholistan Desert [صحرائے چولستان]'
            aliases.append(extra)
    seen: set[str] = set()
    taken = {line1, p.get("line2", {}).get("text"), *(a["text"] for a in alt)}
    aliases = [a for a in aliases if a and a not in taken and not (a in seen or seen.add(a))]
    if aliases:
        p["aliases"] = aliases
    if alt:
        p["alt_names"] = alt
    if includes:
        p["includes"] = includes
    p["lat"], p["lon"] = num(r["lat"]), num(r["lon"])
    p["radius_km"] = num(r["radius_km"])
    p["dune_km2"] = round(float(r["mapped_dune_km2"]))
    # ';' or ',' separated in the table (no country or territory name there contains a comma)
    p["countries"] = [c.strip() for c in re.split(r"[;,]", r["countries_or_territories"]) if c.strip()]
    src: list[str] = []
    for u in split_bar(r["reference_urls"]):
        u = re.sub(r"\s*\([^()]*\bPI library\)", "", u).strip()   # internal holding notes are not shipped
        if u and u not in src:
            src.append(u)
    p["sources"] = src
    return p


HEADER = """# Named places of the search box and the 'Show names' labels (schema: registry/places.schema.json).
# GENERATED by scripts/places/build_earth_places.py from the approved name table
# (earth-dune-field-names-final.csv, October 2026); edit the table and re-run rather than this file.
# line1: the display name; line2: the name in a non-Latin script with its BCP 47 language; aliases: the
# English name and the sub-units (searchable); alt_names: the alternative names (searchable) with their
# script, meaning and language (popup); includes: sub-units (popup); countries: countries or
# territories as given in the table; radius_km: approximate radius (zoom); dune_km2: mapped dune area
# (label size and priority, result ranking); sources: the references, in the table's order.
# note: the naming note (verbatim, approved October 2026; shown in the dune layer's and Show names' info,
# About and under the search results), with note_links marking the text that is a link.
enabled: true
note: "Displayed dune field names are derived from previously published academic research and data, regional knowledge, and internet searches. Naming conventions (language, jurisdiction, spelling, merging, etc.) were chosen for clarity but may be wrong or offend certain peoples. Please contact Andrew Gunn at a.gunn@monash.edu if you have any suggestions for changes, removals, or additions."
note_links: [{"text": "a.gunn@monash.edu", "href": "mailto:a.gunn@monash.edu"}]
credit: "Dune-field names: compiled for the Dune Atlas from the sources listed for each name; for navigation only."
places:
"""


def main(argv: list[str]) -> None:
    src = Path(argv[1])
    out = Path(argv[2]) if len(argv) > 2 else REPO / "registry" / "earth" / "places.yaml"
    with open(src, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    places = [place(r) for r in rows]
    ids = [p["id"] for p in places]
    assert len(set(ids)) == len(ids), "duplicate ids"
    places.sort(key=lambda p: (-p["dune_km2"], p["line1"]))
    # one flow mapping per place (JSON is valid YAML flow syntax): compact and diff-friendly
    body = "".join(f"  - {json.dumps(p, ensure_ascii=False)}\n" for p in places)
    out.write_text(HEADER + body, encoding="utf-8")
    print(f"{out}: {len(places)} places, {out.stat().st_size:,} bytes")


if __name__ == "__main__":
    main(sys.argv)
