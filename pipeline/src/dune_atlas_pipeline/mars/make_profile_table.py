"""Generate profile_table.json: the universal smooth-wall mean velocity profile u+ = u/u* versus X = z u*/nu
from the mixing-length closure of Pahtz & Duran (2023, eq. 2.2) under constant total shear stress
(no transport feedback, smooth wall):

    dl+/dz+ = kappa [1 - exp(-sqrt(u+ l+ / 7))]          (eq. 2.2 in '+' units: l+ = l u*/nu, z+ = z u*/nu)
    (1 + l+^2 du+/dz+) du+/dz+ = 1                        (tau = rho (nu + l^2 |du/dz|) du/dz = rho u*^2)

l+ = 0 is a (trivial) solution, so integration starts on the non-trivial wall branch: for z+ << 1, u+ = z+ and
dl+/dz+ ~ kappa sqrt(z+ l+ / 7), giving l+ = kappa^2 z+^3 / 63. The committed table is the single source of the
profile for the pipeline (physics.py) and the browser (exported into constants-mars.json): never regenerate it
silently; a regeneration is a data-version change.

    PYTHONPATH=pipeline/src python -m dune_atlas_pipeline.mars.make_profile_table
"""
import json
import pathlib

import numpy as np
from scipy.integrate import solve_ivp

from . import constants as M

LNX_MIN, LNX_MAX, N = np.log(1e-2), np.log(1e8), 1201
OUT = pathlib.Path(__file__).with_name("profile_table.json")


def integrate(lnx):
    k, a = M.KAPPA, M.MIX_DAMP

    def rhs(zp, y):
        up, lp = y
        dudz = 2.0 / (1.0 + np.sqrt(1.0 + 4.0 * lp * lp))   # = (sqrt(1+4l^2)-1)/(2l^2), cancellation-free
        return [dudz, k * (1.0 - np.exp(-np.sqrt(max(up * lp, 0.0) / a)))]

    x = np.exp(lnx)
    x0 = x[0]
    sol = solve_ivp(rhs, (x0, x[-1]), [x0, k * k * x0 ** 3 / (9.0 * a)], t_eval=x, method="LSODA",
                    rtol=1e-11, atol=1e-16)
    assert sol.success, sol.message
    return sol.y[0]


def main():
    lnx = np.linspace(LNX_MIN, LNX_MAX, N)
    up = integrate(lnx)
    # log-layer constant c in u+ = ln(c X)/kappa, from the table end
    c = float(np.exp(M.KAPPA * up[-1]) / np.exp(lnx[-1]))
    out = {"_comment": "GENERATED by dune_atlas_pipeline.mars.make_profile_table (eq. 2.2 smooth wall, constant stress)",
           "kappa": M.KAPPA, "damping": M.MIX_DAMP, "ln_x": lnx.tolist(), "u_plus": up.tolist(), "log_layer_c": c}
    OUT.write_text(json.dumps(out) + "\n")
    print(OUT, N, "log-layer c =", round(c, 4))


if __name__ == "__main__":
    main()
